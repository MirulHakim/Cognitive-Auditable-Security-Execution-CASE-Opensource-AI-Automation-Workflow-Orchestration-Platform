"""The Document Generator node.

Renders the run's case data (and any AI output above the step) into HTML, PDF or
DOCX. Files are written under ``DOCUMENT_OUTPUT_DIR`` and served back through
``GET /api/instances/:id/documents/:stepId``.
"""

from __future__ import annotations

import html
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .config import REPO_ROOT, settings

FORMATS = {"html": "html", "pdf": "pdf", "docx": "docx", "word": "docx"}

MIME = {
    "html": "text/html; charset=utf-8",
    "pdf": "application/pdf",
    "docx": "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
}


def _lines(case_input: dict[str, str], ai_outputs: list[dict[str, Any]]) -> list[tuple[str, str]]:
    rows: list[tuple[str, str]] = []
    for key, value in case_input.items():
        rows.append((key, str(value)))
    for index, entry in enumerate(ai_outputs, start=1):
        label = entry.get("stepName") or f"AI output {index}"
        rows.append((label, str(entry.get("output", "")).strip()))
    return rows


def _html(title: str, rows: list[tuple[str, str]], meta: dict[str, str]) -> str:
    body_rows = "\n".join(
        f"""      <tr><th>{html.escape(key)}</th><td>{html.escape(value)}</td></tr>"""
        for key, value in rows
    )
    meta_rows = "\n".join(
        f"""      <tr><th>{html.escape(key)}</th><td>{html.escape(value)}</td></tr>"""
        for key, value in meta.items()
    )
    return f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>{html.escape(title)}</title>
  <style>
    body {{ font-family: Georgia, serif; margin: 3rem auto; max-width: 44rem; color: #1f2933; line-height: 1.55; }}
    h1 {{ font-size: 1.6rem; margin-bottom: 0.25rem; }}
    p.sub {{ color: #6b7280; margin-top: 0; font-size: 0.85rem; }}
    table {{ width: 100%; border-collapse: collapse; margin-top: 1.5rem; font-size: 0.92rem; }}
    th, td {{ text-align: left; padding: 0.55rem 0.7rem; border-bottom: 1px solid #e5e7eb; vertical-align: top; }}
    th {{ width: 32%; color: #4b5563; font-weight: 600; }}
    pre {{ white-space: pre-wrap; margin: 0; font-family: inherit; }}
    footer {{ margin-top: 2rem; font-size: 0.75rem; color: #9ca3af; }}
  </style>
</head>
<body>
  <h1>{html.escape(title)}</h1>
  <p class="sub">Generated by CASE — every step of this run is recorded in the audit trail.</p>
  <table>
{body_rows}
  </table>
  <footer>
    <table>
{meta_rows}
    </table>
  </footer>
</body>
</html>
"""


def _write_pdf(path: Path, title: str, rows: list[tuple[str, str]], meta: dict[str, str]) -> None:
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import getSampleStyleSheet
    from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
    from reportlab.lib import colors

    styles = getSampleStyleSheet()
    story: list[Any] = [
        Paragraph(html.escape(title), styles["Title"]),
        Paragraph(
            "Generated by CASE — every step of this run is recorded in the audit trail.",
            styles["Italic"],
        ),
        Spacer(1, 16),
    ]

    data = [[Paragraph(f"<b>{html.escape(key)}</b>", styles["BodyText"]),
             Paragraph(html.escape(value).replace("\n", "<br/>"), styles["BodyText"])]
            for key, value in rows]
    table = Table(data, colWidths=[150, 330])
    table.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LINEBELOW", (0, 0), (-1, -1), 0.4, colors.HexColor("#e5e7eb")),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
            ]
        )
    )
    story.append(table)
    story.append(Spacer(1, 24))
    meta_table = Table(
        [[Paragraph(f"<b>{html.escape(key)}</b>", styles["BodyText"]),
          Paragraph(html.escape(value), styles["BodyText"])] for key, value in meta.items()],
        colWidths=[150, 330],
    )
    story.append(meta_table)
    SimpleDocTemplate(str(path), pagesize=A4, title=title).build(story)


def _write_docx(path: Path, title: str, rows: list[tuple[str, str]], meta: dict[str, str]) -> None:
    from docx import Document

    document = Document()
    document.add_heading(title, level=1)
    document.add_paragraph("Generated by CASE — every step of this run is recorded in the audit trail.")
    table = document.add_table(rows=0, cols=2)
    table.style = "Light Grid Accent 1"
    for key, value in rows:
        cells = table.add_row().cells
        cells[0].text = key
        cells[1].text = value
    document.add_paragraph("")
    meta_table = document.add_table(rows=0, cols=2)
    for key, value in meta.items():
        cells = meta_table.add_row().cells
        cells[0].text = key
        cells[1].text = value
    document.save(str(path))


def render_document(
    *,
    instance_id: str,
    step_id: str,
    title: str,
    case_input: dict[str, str],
    ai_outputs: list[dict[str, Any]],
    template_format: str = "HTML",
    include_case_input: bool = True,
    include_ai_output: bool = True,
) -> dict[str, Any]:
    fmt = FORMATS.get(str(template_format).lower(), "html")
    rows: list[tuple[str, str]] = []
    if include_case_input:
        rows.extend((key, str(value)) for key, value in case_input.items())
    if include_ai_output:
        rows.extend(_lines({}, ai_outputs))

    output_dir = settings.resolved_document_dir()
    path = output_dir / f"{instance_id}--{step_id}.{fmt}"

    meta = {
        "run": instance_id,
        "step": step_id,
        "format": fmt,
        "generated": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC"),
        "sources": "+".join(
            [name for name, enabled in (("case data", include_case_input), ("AI output", include_ai_output)) if enabled]
        )
        or "none",
    }

    if fmt == "pdf":
        _write_pdf(path, title, rows, meta)
    elif fmt == "docx":
        _write_docx(path, title, rows, meta)
    else:
        path.write_text(_html(title, rows, meta), encoding="utf-8")

    resolved = path.resolve()
    relative = (
        resolved.relative_to(REPO_ROOT).as_posix()
        if resolved.is_relative_to(REPO_ROOT)
        else str(resolved)
    )
    return {
        "file": relative,
        "mode": "generated",
        "bytes": path.stat().st_size,
        "title": title,
        "format": fmt,
        "mimeType": MIME[fmt],
        "contentSource": meta["sources"],
    }


def resolve_document(recorded_path: str) -> Path | None:
    """Resolve a stored path inside the output directory, or ``None``."""
    root = settings.resolved_document_dir()
    candidate = Path(recorded_path)
    if not candidate.is_absolute():
        candidate = REPO_ROOT / candidate
    try:
        resolved = candidate.resolve()
    except OSError:
        return None
    if not resolved.is_relative_to(root.resolve()):
        return None
    return resolved if resolved.is_file() else None
